import { defineAppManifest, defineEndpoint } from "@twodb/core-platform/manifest";
import { z } from "zod";

const sessionOut = z.object({
  id: z.string(),
  type: z.string(),
  title: z.string(),
  runner: z.string(),
  directory: z.string(),
  model: z.string(),
  interactive: z.boolean(),
  spaceId: z.string(),
  agentId: z.string().nullable(),
  parentSessionId: z.string().nullable(),
  createdAt: z.string(),
  updatedAt: z.string(),
});

export const artisanManifest = defineAppManifest({
  name: "Artisan",
  slug: "artisan",
  version: "0.1.0",
  shape: "backend+webapp",
  description: "Coding agent harness — sessions on runner directories, threads, subagents, skills.",
  capabilities: ["ws"],
  websocketPaths: ["/ws", "/sessions/:id/term", "/sessions/:id/editor-ws", "/sessions/:id/editor-ws-path/:path"],
  coreDeps: ["core-data", "core-platform", "core-async"],
  basePath: "/apps/artisan",
  endpoints: [
    defineEndpoint({
      name: "createSession",
      method: "POST",
      path: "/sessions",
      auth: "session-or-apiKey",
      description: "Creates a session bound to a runner directory (any type; type=directory is the default webapp kind). Optional opening message runs immediately.",
      request: z.object({
        spaceId: z.string().optional(),
        type: z.string().optional(),
        title: z.string().optional(),
        runner: z.string(),
        directory: z.string(),
        model: z.string().optional(),
        interactive: z.boolean().optional(),
        agentId: z.string().nullable().optional(),
        message: z.string().optional(),
      }),
      response: sessionOut,
    }),
    defineEndpoint({
      name: "listSessions",
      method: "GET",
      path: "/sessions",
      auth: "session-or-apiKey",
      description: "Sessions, newest first. Defaults to type=directory (webapp list); ?type= picks another, ?all=1 disables the filter.",
      request: z.object({ type: z.string().optional(), runner: z.string().optional(), directory: z.string().optional(), spaceId: z.string().optional(), all: z.string().optional() }),
      response: z.array(sessionOut),
    }),
    defineEndpoint({
      name: "getSession",
      method: "GET",
      path: "/sessions/:id",
      auth: "session-or-apiKey",
      description: "Session + flat messages + usage + plan + running flag. Works for any session type.",
      request: z.object({ id: z.string() }),
      response: sessionOut.extend({
        plan: z.unknown().nullable(),
        running: z.boolean(),
        usage: z.object({ inputTokens: z.number(), outputTokens: z.number(), cachedTokens: z.number(), calls: z.number(), costUsd: z.number().nullable() }).nullable(),
        messages: z.array(z.object({ id: z.string(), role: z.string(), content: z.string(), meta: z.unknown(), createdAt: z.string() })),
      }),
    }),
    defineEndpoint({
      name: "updateSession",
      method: "PATCH",
      path: "/sessions/:id",
      auth: "session-or-apiKey",
      description: "Renames and/or switches the session's model.",
      request: z.object({ id: z.string(), title: z.string().optional(), model: z.string().optional() }),
      response: sessionOut,
    }),
    defineEndpoint({
      name: "sendMessage",
      method: "POST",
      path: "/sessions/:id/messages",
      auth: "session-or-apiKey",
      description: "Sends a user message and starts a run (same as the WS send frame). Stream frames over the workspace WS.",
      request: z.object({ id: z.string(), message: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "newThread",
      method: "POST",
      path: "/sessions/:id/new",
      auth: "session-or-apiKey",
      description: "/new — closes the current thread and opens a fresh one; clears the plan.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "compactSession",
      method: "POST",
      path: "/sessions/:id/compact",
      auth: "session-or-apiKey",
      description: "/compact — summarizes the conversation into the thread summary and starts a new thread.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean(), summary: z.string() }),
    }),
    defineEndpoint({
      name: "abortSession",
      method: "POST",
      path: "/sessions/:id/abort",
      auth: "session-or-apiKey",
      description: "Aborts a running session loop.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "workspaceWs",
      method: "GET",
      path: "/ws",
      auth: "session-or-apiKey",
      description: "One WS per workspace. Client frames: join/leave {sessionId}, send {sessionId,text}, answer/cancel {sessionId,askId}. Server frames all carry sessionId: joined, message, run_start, round_start, thinking_delta, delta, message_done, tool_start/output/result, ask_user, ask_resolved, status, plan, usage, compaction_done, session_renamed, error, done.",
      request: z.object({}),
      response: z.object({}),
    }),
    defineEndpoint({
      name: "listDirectories",
      method: "GET",
      path: "/directories",
      auth: "session-or-apiKey",
      description: "Distinct runner+directory+space combos the workspace has sessions on.",
      request: z.object({}),
      response: z.array(z.object({ runner: z.string(), directory: z.string(), spaceId: z.string(), sessions: z.number() })),
    }),
    defineEndpoint({
      name: "createAgent",
      method: "POST",
      path: "/agents",
      auth: "session-or-apiKey",
      description: "Creates a custom agent (sub_agent | persona | collaborator | any custom type).",
      request: z.object({
        spaceId: z.string().optional(), type: z.string(), name: z.string(), description: z.string().optional(),
        instruction: z.string(), model: z.string().nullable().optional(), tools: z.array(z.string()).optional(),
        skillTags: z.array(z.string()).optional(), tags: z.array(z.string()).optional(),
        runner: z.string().nullable().optional(), directory: z.string().nullable().optional(),
      }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "listAgents",
      method: "GET",
      path: "/agents",
      auth: "session-or-apiKey",
      description: "Agents in a space (directory agents included — they are auto-created per runner+directory).",
      request: z.object({ spaceId: z.string().optional() }),
      response: z.array(z.object({ id: z.string(), type: z.string(), name: z.string(), description: z.string(), model: z.string().nullable(), tools: z.array(z.string()), skillTags: z.array(z.string()), tags: z.array(z.string()), runner: z.string().nullable(), directory: z.string().nullable(), spaceId: z.string() })),
    }),
    defineEndpoint({
      name: "updateAgent",
      method: "PATCH",
      path: "/agents/:id",
      auth: "session-or-apiKey",
      description: "Updates any agent field (instruction, model, tools allowlist, tags, pinned dir).",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "deleteAgent",
      method: "DELETE",
      path: "/agents/:id",
      auth: "session-or-apiKey",
      description: "Deletes an agent.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "createSkill",
      method: "POST",
      path: "/skills",
      auth: "session-or-apiKey",
      description: "Creates a space-scoped skill with optional directory pin and tags.",
      request: z.object({
        spaceId: z.string().optional(), directory: z.string().nullable().optional(), name: z.string(),
        description: z.string(), content: z.string(), tags: z.array(z.string()).optional(),
      }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "listSkills",
      method: "GET",
      path: "/skills",
      auth: "session-or-apiKey",
      description: "Skills in a space.",
      request: z.object({ spaceId: z.string().optional() }),
      response: z.array(z.object({ id: z.string(), name: z.string(), description: z.string(), directory: z.string().nullable(), tags: z.array(z.string()), spaceId: z.string() })),
    }),
    defineEndpoint({
      name: "updateSkill",
      method: "PATCH",
      path: "/skills/:id",
      auth: "session-or-apiKey",
      description: "Updates a skill.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "deleteSkill",
      method: "DELETE",
      path: "/skills/:id",
      auth: "session-or-apiKey",
      description: "Deletes a skill.",
      request: z.object({ id: z.string() }),
      response: z.object({ ok: z.boolean() }),
    }),
    defineEndpoint({
      name: "listModels",
      method: "GET",
      path: "/models",
      auth: "session-or-apiKey",
      description: "Proxied TwoRoute /v1/models — the model picker source.",
      request: z.object({}),
      response: z.array(z.object({ id: z.string(), name: z.string(), provider: z.string(), connection: z.string(), contextWindow: z.number().nullable() })),
    }),
    defineEndpoint({
      name: "listRunners",
      method: "GET",
      path: "/runners",
      auth: "session-or-apiKey",
      description: "Proxied Dispatch runners, online only.",
      request: z.object({}),
      response: z.array(z.object({ name: z.string(), status: z.string(), kind: z.string() })),
    }),
  ],
});

export default artisanManifest;
